/**
 * Blog architecture. Posts are structured data, not raw HTML, so headings stay
 * consistent and every article can be rendered by one component.
 *
 * CONTENT RULE (plan §36): fewer, better articles. Do not pad this list with
 * thin AI-written posts to fill the plan's list of ten titles. Every article
 * must answer a real customer question using verified information — the same
 * standard as the rest of the site. An article that would need invented facts
 * does not get written until the business supplies them.
 */

/** A link inside running text. Internal hrefs start with "/". */
export type InlineLink = { href: string; label: string };

/** Plain text, or text with links woven into it. */
export type Paragraph = string | (string | InlineLink)[];

export type BlogSection = {
  heading: string;
  body: Paragraph[];
  /** Rendered as a checklist under the paragraphs. */
  list?: Paragraph[];
  /** Sub-steps, each an h3 with its own paragraphs, after the list. */
  steps?: { heading: string; body: Paragraph[] }[];
  /** Closing paragraphs, after the list and steps. */
  outro?: Paragraph[];
  /** Visible questions; the page also emits them as FAQPage JSON-LD. */
  faqs?: { question: string; answer: string }[];
};

export type BlogPost = {
  slug: string;
  title: string;
  seoTitle: string;
  description: string;
  /** ISO date — drives <time> and OG publishedTime. */
  publishedAt: string;
  excerpt: string;
  /** A file in public/images, shown beside the title. */
  image?: { file: string; alt: string };
  /** Opening paragraphs, before the first heading. */
  intro?: Paragraph[];
  sections: BlogSection[];
  /** Internal links rendered at the end (CLAUDE.md §6). */
  related: { href: string; label: string }[];
};

const destinationList = countries.map((c) => c.name).join(", ");

/**
 * Country names as the business wrote them, linked where a country page
 * exists. Names stay in the nominative, so nothing is declined (CLAUDE.md §5).
 */
function linkCountries(names: string[]): (string | InlineLink)[] {
  return names.flatMap((name, index) => {
    const country = countries.find((c) => c.name === name);
    const part = country
      ? { href: `/countries/${country.slug}`, label: name }
      : name;
    return index === 0 ? [part] : [", ", part];
  });
}

