export const countriesRu: Country[] = countries.map((country) => {
  const translated = copy[country.slug];

  return {
    ...country,
    ...translated,
    // `source` and `verifiedOn` survive because the Georgian fact is spread first.
    facts: country.facts.map((fact) => ({ ...fact, ...factCopy[fact.id] })),
    content: {
      ...translated.content,
      // Narrative citations are positional, so Russian keeps the same block order.
      narrative: translated.content.narrative?.map((block, index) => ({
        ...block,
        sources: country.content?.narrative?.[index]?.sources,
      })),
    },
  };
});

export const getCountryRu = (slug: string): Country | undefined =>
  countriesRu.find((country) => country.slug === slug);

export function relatedCountriesRu(slug: string, limit = 3): Country[] {
  const index = countriesRu.findIndex((country) => country.slug === slug);
  if (index === -1) return countriesRu.slice(0, limit);
  return [
    ...countriesRu.slice(index + 1),
    ...countriesRu.slice(0, index),
  ].slice(0, limit);
}
